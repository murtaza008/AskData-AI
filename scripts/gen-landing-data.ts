/**
 * Snapshot of real numbers from the demo dataset for the public landing page,
 * which must render without a database. Read-only: it connects as the
 * read-only analytics role and only runs SELECTs.
 *
 *   npx tsx scripts/gen-landing-data.ts   → src/features/marketing/landing-data.json
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { connect, readonlyUrl } from "./lib/db";

const OUT = path.join(process.cwd(), "src/features/marketing/landing-data.json");

// Revenue follows the dataset's business rule: cancelled and refunded orders don't count.
const VALID = "o.status NOT IN ('cancelled', 'refunded')";

async function main() {
  const client = await connect(readonlyUrl());
  try {
    await client.query("BEGIN TRANSACTION READ ONLY");

    const names = ["customers", "products", "orders", "order_items", "refunds"];
    const tables: { name: string; rows: number; columns: number }[] = [];
    for (const name of names) {
      const count = await client.query<{ rows: number }>(`SELECT count(*)::int AS rows FROM analytics.${name}`);
      const columns = await client.query<{ columns: number }>(
        `SELECT count(*)::int AS columns FROM information_schema.columns WHERE table_schema = 'analytics' AND table_name = $1`,
        [name],
      );
      tables.push({ name, rows: count.rows[0].rows, columns: columns.rows[0].columns });
    }

    const latest = await client.query<{ latest: string }>(
      `SELECT max(order_date)::date::text AS latest FROM analytics.orders`,
    );
    const latestDate = latest.rows[0].latest;

    // "Last month" relative to the newest order in the data: the last complete calendar month.
    const month = await client.query<{ start: string; label: string }>(
      `SELECT (date_trunc('month', $1::date) - interval '1 month')::date::text AS start,
              to_char(date_trunc('month', $1::date) - interval '1 month', 'FMMonth YYYY') AS label`,
      [latestDate],
    );
    const { start, label } = month.rows[0];

    const products = await client.query<{ product: string; category: string; revenue: number; units: number }>(
      `SELECT p.name AS product, p.category, round(sum(oi.quantity * oi.unit_price), 2)::float AS revenue,
              sum(oi.quantity)::int AS units
       FROM analytics.order_items oi
       JOIN analytics.orders o ON o.id = oi.order_id
       JOIN analytics.products p ON p.id = oi.product_id
       WHERE ${VALID} AND o.order_date >= $1::date AND o.order_date < $1::date + interval '1 month'
       GROUP BY p.name, p.category
       ORDER BY revenue DESC
       LIMIT 5`,
      [start],
    );

    const monthly = await client.query<{ month: string; revenue: number; orders: number }>(
      `SELECT to_char(date_trunc('month', o.order_date), 'YYYY-MM') AS month,
              round(sum(o.total_amount), 2)::float AS revenue, count(*)::int AS orders
       FROM analytics.orders o
       WHERE ${VALID} AND o.order_date >= date_trunc('month', $1::date) - interval '11 months'
         AND o.order_date < date_trunc('month', $1::date)
       GROUP BY 1 ORDER BY 1`,
      [latestDate],
    );

    const regions = await client.query<{ region: string; revenue: number }>(
      `SELECT c.region, round(sum(o.total_amount), 2)::float AS revenue
       FROM analytics.orders o JOIN analytics.customers c ON c.id = o.customer_id
       WHERE ${VALID} GROUP BY c.region ORDER BY revenue DESC`,
    );

    const channels = await client.query<{ channel: string; orders: number; aov: number }>(
      `SELECT o.channel, count(*)::int AS orders, round(avg(o.total_amount), 2)::float AS aov
       FROM analytics.orders o WHERE ${VALID} GROUP BY o.channel ORDER BY orders DESC`,
    );

    await client.query("ROLLBACK");

    const snapshot = {
      note: "Generated by scripts/gen-landing-data.ts from the demo dataset (read-only). Do not edit by hand.",
      latestOrderDate: latestDate,
      lastMonth: { start, label },
      tables,
      topProducts: products.rows,
      monthlyRevenue: monthly.rows,
      revenueByRegion: regions.rows,
      ordersByChannel: channels.rows,
    };
    writeFileSync(OUT, `${JSON.stringify(snapshot, null, 2)}\n`);
    console.log(`Wrote ${path.relative(process.cwd(), OUT)} (latest order ${latestDate}, last month ${label}).`);
  } finally {
    await client.end();
  }
}

main().catch((error) => {
  console.error(error);
  process.exit(1);
});
